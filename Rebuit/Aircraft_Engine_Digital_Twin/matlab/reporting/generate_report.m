function filename = generate_report(result,comparison,selection,mlMetrics,folder)
%GENERATE_REPORT Export an auditable HTML session report from actual backend outputs.
% Inputs: result struct, comparison table, selection struct, ML table, optional folder.
% Outputs: self-contained HTML plus JSON. Ref: ABACUS 27; absent results are explicit.
p=project_paths(); if nargin<5, folder=fullfile(p.reports,'session'); end
if ~isfolder(folder), mkdir(folder); end
c=project_config();
html=['<!doctype html><html><head><meta charset="utf-8"><title>ABACUS session report</title>',...
    '<style>body{font:14px Arial;max-width:1200px;margin:36px auto;color:#183047}h1,h2{color:#143e60}',...
    'table{border-collapse:collapse;max-width:100%;font-size:11px}td,th{border:1px solid #ccd6df;padding:6px;word-break:break-word}',...
    'th{background:#edf3f8}.warning{background:#fff1d0;padding:16px}section{margin:28px 0;overflow:auto}</style></head><body>',...
    '<h1>Aircraft Engine Performance Analysis</h1><p>',html_escape(c.Scope),' | ',html_escape(utc_timestamp()),'</p>',...
    '<p class="warning">Academic estimates and steady-state simulations. No flight-planning, hardware or certification capability. ',...
    'Synthetic-data surrogate accuracy is separate from real-engine validation.</p>'];
if isfield(result,'Condition')
    html=[html,'<section><h2>Inputs and selected engine</h2><p>',html_escape(result.Engine),' | ',...
        html_escape(result.Prediction_Source),' | ',html_escape(result.Confidence),' confidence</p>',...
        table_to_html(struct2table(result.Condition)),'<h2>Calculated outputs</h2>',...
        table_to_html(format_result_metrics(result,'SI')),'<p class="warning">',...
        html_escape(strjoin(result.Warnings,' | ')),'</p><h2>Station total properties</h2>',...
        table_to_html(result.Stations),'<h2>Parameter provenance</h2>',table_to_html(result.Provenance),'</section>'];
end
html=[html,'<section><h2>Comparison / current data</h2>',table_to_html(comparison),'</section>'];
if isfield(selection,'Message')
    html=[html,'<section><h2>Mission selection</h2><p>',html_escape(selection.Message),'</p>',...
        table_to_html(selection.Ranking),'<h3>Eliminated candidates and reasons</h3>',table_to_html(selection.Eliminated),'</section>'];
end
html=[html,'<section><h2>ML held-out physics metrics (Track B)</h2>',table_to_html(mlMetrics),...
    '</section><h2>Model assumptions</h2><p>Constant component efficiencies, constant specific heats, simplified corrected airflow and throttle schedules, ',...
    'separate exhaust, converging nozzles and simplified propeller treatment. Read docs/ASSUMPTIONS.md and CHANGELOG.md for all resolutions.</p></body></html>'];
filename=fullfile(folder,'ABACUS_session_report.html'); write_text(filename,html);
session=struct('Result',result,'Comparison',comparison,'MissionSelection',selection,'MLMetrics',mlMetrics);
write_text(fullfile(folder,'ABACUS_session_data.json'),jsonencode(session,'PrettyPrint',true));
end
