function r = result_template(e,f)
%RESULT_TEMPLATE Define one output contract for physics, ML and error paths.
% Inputs: engine and flight structures. Output: r with SI fields and explicit status.
% NaN denotes unavailable/inapplicable quantities, never a valid predicted value.
c = project_config();
r = struct('Engine_ID',e.ID,'Engine',e.Name,'Architecture',e.Type,'Condition',f,...
    'Valid',false,'Status','FAIL','Error_Code','','Warnings',strings(0,1),...
    'Data_Type','Simulated','Prediction_Source','Physics','Confidence',e.Confidence,...
    'Model_Version',c.Version,'Model_Fingerprint',e.Fingerprint,'Timestamp_UTC',utc_timestamp(),...
    'Thrust_N',NaN,'EquivalentThrust_N',NaN,'ShaftPower_kW',NaN,'PropShaftPower_kW',NaN,...
    'FuelFlow_kgs',NaN,'TSFC_kgNs',NaN,'BSFC_kgkWh',NaN,'Eta_thermal',NaN,...
    'Eta_propulsive',NaN,'Eta_overall',NaN,'ESHP',NaN,'T_t4_K',NaN,'P_t3_Pa',NaN,...
    'Core_Nozzle_State','N/A','Bypass_Nozzle_State','N/A','Stations',table(),...
    'Diagnostics',struct(),'Provenance',e.Provenance,'Elapsed_ms',NaN,'ML_Model_Type','');
if e.Estimated, r.Data_Type = 'Simulated_Estimated'; end
end
